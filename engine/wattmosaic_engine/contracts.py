class Measurement(Model):
    """One observed CT or device reading.

    ``value`` is in ``unit``; power is normalised to W before entering the
    solver.  ``repeated`` marks a state update whose numeric value is unchanged
    from the previous observation — the engine must not treat it as a new
    physical measurement.
    """

    entity_id: str
    ct_id: str
    value: float
    unit: Literal["W", "kW", "kWh", "Wh"] = "W"
    value_w: float | None = None
    state_timestamp: datetime
    received_at: datetime = Field(default_factory=utcnow)
    physical_timestamp: datetime | None = None
    quality: QualityStatus = QualityStatus.GOOD
    repeated: bool = False
    polarization: Polarity = Polarity.NORMAL
    sequence: int = 0

    @field_validator("value")
    @classmethod
    def _finite(cls, v: float) -> float:
        if v != v or v in (float("inf"), float("-inf")):
            raise ValueError("measurement must be finite")
        return v

    def effective_power_w(self) -> float:
        """Power in watts after unit conversion and polarity. Sign preserved."""
        raw = self.value_w if self.value_w is not None else self.value
        if self.unit == "kW" and self.value_w is None:
            raw = self.value * 1000.0
        sign = -1.0 if self.polarization == Polarity.INVERTED else 1.0
        return raw * sign


class CTChannel(Model):
    ct_id: str
    entity_id: str
    name: str | None = None
    ct_type: CTType = CTType.UNKNOWN
    phase: Phase = Phase.UNKNOWN
    # Containment.  Any CT may sit under any other CT, to any depth: a panel
    # feed under the service feed, a sub-panel feed under the panel feed, a
    # branch under a sub-panel, and so on.  Nesting is a wiring fact; the engine
    # never invents it and always requires ``TopologyStatus.CONFIRMED`` before
    # a nested total is presented as authoritative.
    parent_ct_id: str | None = None
    polarity: Polarity = Polarity.NORMAL
    device_id: str | None = None
    enabled: bool = True
    # Paired CT for a single double-pole load: this CT is one leg.
    paired_ct_id: str | None = None
    # Set on a CT that measures *the same conductor* as another CT (two monitors
    # clamped on one service entrance).  Only the canonical channel contributes
    # to a total; the alias is still usable for its own device readings.
    alias_of_ct_id: str | None = None
    # Scaling applied to the reported reading, for the "circuit multiplier" case
    # some CT monitors expose: one CT on one leg of a 240 V load, doubled in
    # software by the monitor itself.
    #
    # Defaults to 1.0 because the monitor commonly applies the multiplier
    # itself and already publishes the full load.  Multiplying again would
    # double-count, so this is never inferred from ``phase`` or ``ct_type`` --
    # it is a per-circuit user declaration.
    measurement_multiplier: float = 1.0
    # Optional nominal voltage for current-only channels.
    nominal_voltage: float | None = None
    resolution_w: float | None = None
    expected_interval_s: float | None = None
    reliability: float = 1.0
    topology_status: TopologyStatus = TopologyStatus.CANDIDATE
    metadata: dict[str, Any] = Field(default_factory=dict)

    @field_validator("measurement_multiplier")
    @classmethod
    def _multiplier_must_be_positive_finite(cls, v: float) -> float:
        """Reject a multiplier that would zero, invert or explode a reading.

        A multiplier is a *scaling* declaration for one leg of a split load.  It
        must never be zero (which would silently hide the circuit), negative
        (which would look like export), or non-finite.  Values below 1.0 are
        allowed but unusual, so they are not rejected.
        """
        value = float(v)
        if value != value or value in (float("inf"), float("-inf")):
            raise ValueError("measurement_multiplier must be finite")
        if value <= 0.0:
            raise ValueError("measurement_multiplier must be greater than zero")
        return value

    @model_validator(mode="after")
    def _alias_is_not_self(self) -> CTChannel:
        if self.alias_of_ct_id is not None and self.alias_of_ct_id == self.ct_id:
            raise ValueError("a CT cannot be an alias of itself")
        return self


class DeviceTopology(Model):
    """Where in the electrical tree a logical device sits.

    A device may sit under multiple branch CTs only if that is genuinely true
    (redundant CTs); normally exactly one branch path applies.
    """

    device_id: str
    name: str | None = None
    dedicated_ct_ids: list[str] = Field(default_factory=list)
    branch_ct_ids: list[str] = Field(default_factory=list)
    phase: Phase = Phase.UNKNOWN
    double_pole: bool = False
    parent_device_id: str | None = None
    topology_status: TopologyStatus = TopologyStatus.CANDIDATE
    metadata: dict[str, Any] = Field(default_factory=dict)


class Topology(Model):
    version: int = 1
    created_at: datetime = Field(default_factory=utcnow)
    status: TopologyStatus = TopologyStatus.CANDIDATE
    channels: list[CTChannel] = Field(default_factory=list)
    devices: list[DeviceTopology] = Field(default_factory=list)
    notes: list[str] = Field(default_factory=list)

    def channel_map(self) -> dict[str, CTChannel]:
        return {c.ct_id: c for c in self.channels}

    def device_map(self) -> dict[str, DeviceTopology]:
        return {d.device_id: d for d in self.devices}


# --------------------------------------------------------------------------- #
# Per-device configuration (ADR-0011 / ADR-0012)
# --------------------------------------------------------------------------- #
#
# Configuration is *declarative user knowledge*, never an inference.  It is what
# lets the engine attribute power it could not otherwise attribute honestly:
# knowing that a circuit has four 9 W LEDs means a positive residual on that
# circuit is explainable at 36 W rather than being an anonymous blob.  Nothing
# here is derived from a name, an HA area or the registry.


class ExpectedPower(Model):
    """Watt envelopes the user asserts for a device.

    Every field is optional: an absent field means "not stated", never zero.
    """

    on_w: float | None = Field(default=None, ge=0.0)
    idle_w: float | None = Field(default=None, ge=0.0)
    standby_w: float | None = Field(default=None, ge=0.0)
    startup_w: float | None = Field(default=None, ge=0.0)
    shutdown_w: float | None = Field(default=None, ge=0.0)
    #: Absolute tolerance for matching a measurement to ``on_w``.
    tolerance_w: float | None = Field(default=None, ge=0.0)
    #: Relative tolerance, applied to the larger of ``on_w`` and 1 W.
    tolerance_fraction: float | None = Field(default=None, ge=0.0, le=1.0)

    def tolerance(self) -> float:
        """Absolute tolerance in W, defaulting to 10 % with a 2 W floor."""
        rel = 0.10 if self.tolerance_fraction is None else self.tolerance_fraction
        base = max(abs(self.on_w or 0.0), 1.0)
        floor = 2.0 if self.tolerance_w is None else self.tolerance_w
        return max(floor, rel * base)


class LightConfiguration(Model):
    """Advanced light detail — the highest-value confidence lever in a house
    with 81 dimmable ``light.*`` entities."""

    light_type: LightType = LightType.UNKNOWN
    #: Number of lamps behind one logical light/group.  A five-bulb fixture at
    #: 9 W per bulb is 45 W, not 9 W.
    bulb_count: int = Field(default=1, ge=1, le=200)
    #: Watts drawn by one lamp at full output (per bulb, not per fixture).
    watts_per_bulb_on: float | None = Field(default=None, ge=0.0)
    #: ``0 W`` while off — true for every conventional fixture; kept explicit
    #: because a smart bulb's *radio* still draws power while the light is off.
    standby_w: float | None = Field(default=None, ge=0.0)
    #: Minimum non-zero output: dimmers usually cannot go below a few percent.
    min_output_fraction: float | None = Field(default=None, ge=0.0, le=1.0)
    #: Optional measured dimming curve, ``[brightness_fraction, watt_fraction]``
    #: ascending.  When absent the engine assumes linear output (documented).
    dimming_curve: list[tuple[float, float]] = Field(default_factory=list)

    @field_validator("dimming_curve")
    @classmethod
    def _curve_ascending(cls, v: list[tuple[float, float]]) -> list[tuple[float, float]]:
        xs = [float(x) for x, _ in v]
        if any(b < a for a, b in zip(xs, xs[1:], strict=False)):
            raise ValueError("dimming_curve x values must be ascending")
        return v

    def full_on_w(self) -> float | None:
        """Fixture watts at full output, or ``None`` when not configured."""
        if self.watts_per_bulb_on is None:
            return None
        return float(self.watts_per_bulb_on) * self.bulb_count


class ControllerStateRole(str, Enum):
    """What one label of a multi-state controller means for *load*."""

    LOAD = "load"
    """This label means the appliance is actually drawing power."""

    MODE = "mode"
    """Context only: selects a profile, proves nothing about runtime."""

    OFF = "off"
    """This label means no load."""

    IGNORE = "ignore"
    """No meaning; e.g. ``unavailable``."""


class ControllerStateMapping(Model):
    label: str
    role: ControllerStateRole = ControllerStateRole.MODE
    #: Watts while this label holds.  Only honoured when ``role == "load"`` and
    #: ``confirmed`` is true — this is the "model can estimate" path, and it is
    #: opt-in precisely because a thermostat emits ``heat_cool`` in 1845 of 1848
    #: rows regardless of whether equipment runs.
    power_w: float | None = Field(default=None, ge=0.0)
    confirmed: bool = False

    @field_validator("label")
    @classmethod
    def _non_empty(cls, v: str) -> str:
        text = str(v).strip()
        if not text:
            raise ValueError("controller state label must not be empty")
        return text


class ControllerConfiguration(Model):
    """Multi-state / delayed controller detail (ADR-0012).

    ``mode_entity_id`` never contributes load by itself.  ``load_entity_ids``
    are the declared signals that do prove runtime.
    """

    mode_entity_id: str | None = None
    load_entity_ids: list[str] = Field(default_factory=list)
    states: list[ControllerStateMapping] = Field(default_factory=list)
    #: Delay between the control signal and observable load.  Samples inside
    #: the delay are not evidence either way.
    on_delay_s: float | None = Field(default=None, ge=0.0)
    off_delay_s: float | None = Field(default=None, ge=0.0)
    #: ``False`` when the user knows the appliance ignores the signal (e.g. the
    #: water heater runs on its own aquastat); ``None`` means unstated.
    obeys_control: bool | None = None

    def load_states(self) -> dict[str, float]:
        """Confirmed ``label -> watts`` pairs that may drive a power estimate."""
        return {
            s.label.strip().lower(): float(s.power_w)
            for s in self.states
            if s.role == ControllerStateRole.LOAD
            and s.confirmed
            and s.power_w is not None
        }

    def roles(self) -> dict[str, str]:
        return {
            s.label.strip().lower(): str(s.role) for s in self.states
        }


class DeviceConfiguration(Model):
    """Everything the user can state about one device.

    All three taxonomy axes carry an explicit ``unknown`` so a partially filled
    configuration is honest rather than silently defaulted.
    """

    device_id: str
    device_type: DeviceType = DeviceType.UNKNOWN

    # -- axis 1: HA connectivity ------------------------------------------
    connectivity: HaConnectivity = HaConnectivity.UNKNOWN
    #: Entities that describe runtime.  Empty for ``NOT_CONNECTED``.
    state_entity_ids: list[str] = Field(default_factory=list)
    #: Entities whose state is a *mode*, never proof of load (ADR-0012).
    mode_entity_ids: list[str] = Field(default_factory=list)
    #: Entities that may be actuated.  Informational only — WattMosaic never
    #: calls a service (ADR-0002).
    controllable_entity_ids: list[str] = Field(default_factory=list)

    # -- axis 2: monitoring ------------------------------------------------
    monitoring: MonitoringLevel = MonitoringLevel.UNKNOWN
    #: CTs the user asserts observe this device.  When ``monitoring`` is
    #: ``SHARED`` there must be more than one device on the shared circuit;
    #: the ambiguity is preserved, never resolved by naming.
    monitored_by_ct_ids: list[str] = Field(default_factory=list)

    # -- axis 3: power behaviour ------------------------------------------
    behavior: PowerBehavior = PowerBehavior.UNKNOWN
    expected: ExpectedPower = Field(default_factory=ExpectedPower)
    light: LightConfiguration | None = None
    controller: ControllerConfiguration | None = None

    # -- bookkeeping -------------------------------------------------------
    #: Where the configuration came from, for audit.  ``user`` is the only
    #: value that may raise a confidence tier.  ``auto`` is a correlation the
    #: engine derived from observed co-movement (ADR-0024): it is stored exactly
    #: like a user declaration so attribution behaves the same, but it never
    #: counts as the user having asserted anything, and it is always retractable
    #: without touching what the user wrote.
    configured_by: Literal["user", "import", "default", "auto"] = "user"
    notes: list[str] = Field(default_factory=list)

    @property
    def is_user_asserted(self) -> bool:
        """True only for a declaration a person actually made.

        Anything the engine inferred for itself -- including auto-discovered
        placement -- must not be presented as user knowledge or used to promote
        evidence, however good the correlation looked.
        """
        return self.configured_by == "user"

    @field_validator("device_id")
    @classmethod
    def _device_id_non_empty(cls, v: str) -> str:
        text = str(v).strip()
        if not text:
            raise ValueError("device_id must not be empty")
        return text

    @model_validator(mode="after")
    def _consistent_axes(self) -> DeviceConfiguration:
        if self.connectivity == HaConnectivity.NOT_CONNECTED and self.state_entity_ids:
            raise ValueError(
                "a device that is not connected to Home Assistant cannot declare "
                "state_entity_ids (it has no HA entity); use monitored_by_ct_ids"
            )
        if self.behavior == PowerBehavior.COMPLEX and self.controller is None:
            raise ValueError(
                "behavior=complex requires a controller configuration "
                "(mode entity, load entities and/or confirmed state powers)"
            )
        if self.light is not None and self.device_type not in (
            DeviceType.LIGHT,
            DeviceType.LIGHT_GROUP,
            DeviceType.UNKNOWN,
        ):
            raise ValueError(
                f"light configuration is not valid for device_type={self.device_type}"
            )
        if (
            self.device_type == DeviceType.LIGHT_GROUP
            and self.light is not None
            and self.light.bulb_count < 1  # pragma: no cover - validated above
        ):
            raise ValueError("a light group needs at least one bulb")
        # A ``climate``/``water_heater`` entity listed as a state entity is not
        # rejected: declaring it is the natural mistake and it is reclassified as
        # mode context deterministically (``configuration._split_entities``)
        # rather than silently treated as runtime evidence (ADR-0012).
        return self

    def load_entity_ids(self) -> list[str]:
        """Entities that may prove runtime (state entities + controller loads)."""
        out = list(self.state_entity_ids)
        if self.controller is not None:
            out.extend(self.controller.load_entity_ids)
        seen: set[str] = set()
        return [e for e in out if not (e in seen or seen.add(e))]


class DeviceConfigurationSet(Model):
    """Persisted, versioned collection of per-device configurations."""

    version: int = 1
    updated_at: datetime = Field(default_factory=utcnow)
    devices: list[DeviceConfiguration] = Field(default_factory=list)

    def by_device(self) -> dict[str, DeviceConfiguration]:
        return {d.device_id: d for d in self.devices}

    def get(self, device_id: str) -> DeviceConfiguration | None:
        return self.by_device().get(device_id)

    @model_validator(mode="after")
    def _unique_devices(self) -> DeviceConfigurationSet:
        seen: set[str] = set()
        for device in self.devices:
            if device.device_id in seen:
                raise ValueError(f"duplicate device configuration: {device.device_id}")
            seen.add(device.device_id)
        return self


