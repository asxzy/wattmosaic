class ConfidenceTier(str, Enum):
    """Ordered evidence grade for a device power value (ADR-0013).

    A *grade*, not a probability.  ``InferenceResult.confidence`` remains the
    finer-grained engineering score; the tier answers "what kind of evidence
    produced this number?" without requiring the reader to interpret decimals.
    """

    TIER_0_UNKNOWN = "tier_0_unknown"
    """No evidence supports a device-level value."""

    TIER_1_MODELLED = "tier_1_modelled"
    """Only a model or a configured prior supports the value; nothing live
    independently confirms it."""

    TIER_2_INFERRED = "tier_2_inferred"
    """Separated from shared/bulk CT rows, but no independent corroboration."""

    TIER_3_MEASURED = "tier_3_measured"
    """A dedicated CT measured it, or a declared load signal corroborates a
    shared-channel estimate."""

    TIER_4_VERIFIED = "tier_4_verified"
    """Measured *and* independently corroborated by a declared load signal or a
    validated model agreeing within tolerance, on a fresh sample."""


#: Ascending trust order.  ``rank`` is what comparisons use.
TIER_RANK: dict[ConfidenceTier, int] = {
    ConfidenceTier.TIER_0_UNKNOWN: 0,
    ConfidenceTier.TIER_1_MODELLED: 1,
    ConfidenceTier.TIER_2_INFERRED: 2,
    ConfidenceTier.TIER_3_MEASURED: 3,
    ConfidenceTier.TIER_4_VERIFIED: 4,
}


