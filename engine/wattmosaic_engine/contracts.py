"""Authoritative WattMosaic data contracts (single source of truth).

Any component that exchanges data with another component imports these models.
Subagents MUST NOT invent parallel schemas.  When a contract changes:

1. Edit this module and bump ``CONTRACT_VERSION``.
2. Update ``data/schemas/*.json`` (generated by ``tools/dev/export_schemas.py``).
3. Update affected implementations and run ``pytest``.

Design notes
------------
* ``power_w`` is always watts (W). kW conversion happens at ingestion.
* Sign is preserved.  Negative power means export/reverse flow; it is never
  clamped to zero.
* Every measurement carries *three* timestamps: the Home Assistant state
  timestamp, the engine receipt time, and (when known) a physical sample time.
* ``source`` describes *how* a device power was obtained, never how confident
  we are.  Confidence is separate.
"""

