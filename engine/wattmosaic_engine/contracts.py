# --------------------------------------------------------------------------- #
# Device taxonomy — three *orthogonal* axes (ADR-0011)
# --------------------------------------------------------------------------- #
#
# A device is described simultaneously by all three axes.  They are independent:
# a non-smart garage opener can still sit on a dedicated CT and behave as a
# fixed-watt load, while a smart dimmable light can be visible only through the
# home total.  Do not collapse them into one enum.


class HaConnectivity(str, Enum):
    """Axis 1 — can Home Assistant observe/actuate the device itself?"""

    CONNECTED = "connected"
    """HA holds an entity for the device and may be able to start it."""

    NOT_CONNECTED = "not_connected"
    """Non-smart device: no HA entity describes it.  Only its CT is visible."""

    UNKNOWN = "unknown"


class MonitoringLevel(str, Enum):
    """Axis 2 — how closely does the electrical tree observe the device?"""

    DEDICATED = "dedicated"
    """A CT measures this device and nothing else (``CTType.DEDICATED_DEVICE``)."""

    SHARED = "shared"
    """A sub-meter CT carries this device plus others (e.g. one light on a
    ``lights`` circuit).  Power must be separated from the siblings."""

    HOME_TOTAL_ONLY = "home_total_only"
    """No sub-meter: the device is only inside the home energy monitor total."""

    UNMONITORED = "unmonitored"
    """No CT observes it at all; values can only come from a configured prior."""

    UNKNOWN = "unknown"


class PowerBehavior(str, Enum):
    """Axis 3 — how does power relate to the device's control state?"""

    FIXED = "fixed"
    """Constant watts while running/idle (always-on lamp, garage opener)."""

    VARIABLE = "variable"
    """Power varies with a control value (dimmable light, variable-speed fan).
    The control may live inside or outside Home Assistant."""

    COMPLEX = "complex"
    """A controller with several coupled states (e.g. a thermostat's fan/
    ventilation/humidifier).  The emitted control signal does *not* prove the
    appliance is drawing power: it may have its own switch or a delayed on/off.
    Mode entities are therefore context only, never load evidence (ADR-0012)."""

    UNKNOWN = "unknown"


